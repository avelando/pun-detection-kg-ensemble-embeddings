    has_homograph = any(bool(s.get("homograph", False)) for s in signs)
    has_homophone = any(bool(s.get("homophone", False)) for s in signs)
    has_both = any(
        bool(s.get("homograph", False)) and bool(s.get("homophone", False))
        for s in signs
    )

    if has_both:
        return "ambos"
    if has_homograph:
        return "homografos"
    if has_homophone:
        return "homonimos"
    return "nenhum"

