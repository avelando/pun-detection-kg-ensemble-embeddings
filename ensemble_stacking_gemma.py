def fingerprint_texts(texts):
    h = hashlib.sha1()
    for t in texts:
        t = t if isinstance(t, str) else str(t)
        b = t.encode("utf-8", errors="ignore")
        h.update(len(b).to_bytes(8, "little"))
        h.update(b)
    return h.hexdigest()

def cache_path(split_name, texts, model_name):
    safe = re.sub(r"[^a-zA-Z0-9._-]+", "_", model_name)
    fp = fingerprint_texts(texts)
    return CACHE_DIR / f"emb_{safe}_{split_name}_{fp}.npz"

